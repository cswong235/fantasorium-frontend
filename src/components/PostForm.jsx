import { useState } from 'react';
import { Button, Container, Form } from 'react-bootstrap';
import { apiFetch } from '../services/helpers';
import { useAuth } from '../context/AuthContext';
import { supabase } from '../supabaseClient';

export default function PostForm({ fetchPosts }){
    const { session, user } = useAuth();
    const [title, setTitle] = useState('');
    const [content, setContent] = useState('');
    const [visibility, setVisibility] = useState('public');
    const [file, setFile] = useState(null);
    const [loading, setLoading] = useState(false);
    const [error, setError] = useState('');

    async function handleSubmit(e){
        e.preventDefault();
        const form = e.currentTarget;
        setError('');
        setLoading(true);
        try{
            // Initialize image URL as null since it's optional
            let imageUrl = null;
            // if file exists, upload it to Supabase Storage
            if(file){
                // Autogenerated file name
                const path = `${user.id}/${Date.now()}-${file.name}`;

                // Upload photo to Supabase Storage in the "post-photos" bucket
                const { error: uploadError } = await supabase.storage
                    .from('post-photos')
                    .upload(path, file, { cacheControl: '0' });

                // If there's an error, stop upload
                if(uploadError){
                    setError('Upload failed.');
                    return;
                }

                // Get the URL linked to the image to store into the database later
                imageUrl = supabase.storage.from('post-photos').getPublicUrl(path).data.publicUrl;
            }

            // Submit post with the input details
            await apiFetch('/posts', {
                method: 'POST',
                body: {
                    title: title,
                    content: content,
                    visibility: visibility,
                    image: imageUrl,
                },
                token: session.access_token,
            });
            // Clear the form and refresh the feed so the new post shows up
            setTitle('');
            setContent('');
            setVisibility('public');
            setFile(null);
            form.reset(); // also clears the file input, which state can't control
            fetchPosts();
        }catch(err){
            setError(err.message);
        }finally{
            setLoading(false);
        }
    }

    return(
        <Container>
            <Form onSubmit={handleSubmit}>
                <Form.Group className="mb-3" controlId="postTitle">
                    <Form.Label>Title</Form.Label>
                    <Form.Control
                        type="text"
                        value={title}
                        onChange={(e) => setTitle(e.target.value)}
                        required
                    />
                </Form.Group>

                <Form.Group className="mb-3" controlId="postContent">
                    <Form.Label>Content</Form.Label>
                    <Form.Control
                        as="textarea"
                        rows={4}
                        value={content}
                        onChange={(e) => setContent(e.target.value)}
                        required
                    />
                </Form.Group>

                <Form.Group className="mb-3" controlId="postImage">
                    <Form.Label>Image (optional)</Form.Label>
                    <Form.Control
                        type="file"
                        accept="image/jpeg,image/png,image/webp"
                        onChange={(e) => setFile(e.target.files[0] || null)}
                    />
                </Form.Group>

                <Form.Group className="mb-3">
                    <Form.Label>Who can see this?</Form.Label>
                    <div>
                        <Form.Check
                            inline
                            type="radio"
                            id="visibility-public"
                            name="visibility"
                            label="Public"
                            value="public"
                            checked={visibility === 'public'}
                            onChange={(e) => setVisibility(e.target.value)}
                        />
                        <Form.Check
                            inline
                            type="radio"
                            id="visibility-friends"
                            name="visibility"
                            label="Friends only"
                            value="friends_only"
                            checked={visibility === 'friends_only'}
                            onChange={(e) => setVisibility(e.target.value)}
                        />
                    </div>
                </Form.Group>

                {error && <p className="text-danger">{error}</p>}

                <Button type="submit" disabled={loading}>
                    {loading ? 'Posting...' : 'Post'}
                </Button>
            </Form>
        </Container>
    )
}